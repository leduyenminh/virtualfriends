import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

// In dev, proxy API/WebSocket/OAuth/local files to Spring Boot so everything is same-origin (as behind CloudFront).
// VCHAT_API overrides the backend address, e.g. VCHAT_API=http://localhost:8081
const api = process.env.VCHAT_API ?? 'http://localhost:8080';

/**
 * Content-Security-Policy for the production build: the main defence against XSS. Even if an attacker manages to
 * inject markup, the browser refuses to run any script that isn't one of our bundles or an allow-listed SDK.
 * Not applied in dev because Vite's hot reload injects inline scripts.
 */
const CSP = [
  "default-src 'self'",
  // our bundles + Live2D Cubism core + Google Picker / Identity + OneDrive picker (cloud sticker import);
  // 'wasm-unsafe-eval' lets the offline-history worker compile SQLite's WebAssembly (it does not allow eval())
  "script-src 'self' 'wasm-unsafe-eval' https://cubism.live2d.com https://apis.google.com https://accounts.google.com https://www.gstatic.com https://js.live.net",
  "style-src 'self' 'unsafe-inline' https://accounts.google.com", // React style={{...}} attributes
  "img-src 'self' data: blob: https:",           // stickers/avatars from the media CDN, OAuth profile pictures
  "media-src 'self' data: blob: https:",         // voice notes, TTS audio
  "font-src 'self' data:",
  "connect-src 'self' https: wss:",              // API + WebSocket (same origin), media CDN, Google Drive/OneDrive downloads
  "frame-src 'self' https:",                     // sandboxed Unity iframe on the media domain, Google/OneDrive pickers
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join('; ');

const cspPlugin = {
  name: 'vchat-csp',
  apply: 'build',
  transformIndexHtml: () => [{ tag: 'meta', attrs: { 'http-equiv': 'Content-Security-Policy', content: CSP }, injectTo: 'head-prepend' }],
};

/**
 * Service worker for the production build, so the app opens without a network and can show the offline chat history.
 * It precaches every built file. Pages are network-first, so an online load always gets the latest deploy; the hashed
 * /assets/ files never change and are served from the cache. API, WebSocket and uploaded files are never cached.
 * A new version takes over once all tabs of the old one are closed, so a running page never mixes two builds.
 */
const swPlugin = {
  name: 'vchat-sw',
  apply: 'build',
  writeBundle(options, bundle) {
    const files = Object.keys(bundle).filter((f) => f.startsWith('assets/') && !f.endsWith('.map')).map((f) => `/${f}`);
    const precache = ['/', ...files.sort()];
    const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12);
    writeFileSync(join(options.dir, 'sw.js'), `// Generated by vite.config.js (vchat-sw). Do not edit.
const CACHE = 'vchat-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('vchat-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('/', { cacheName: CACHE })));
  } else if (url.pathname.startsWith('/assets/')) {
    e.respondWith(caches.match(req, { cacheName: CACHE }).then((hit) => hit || fetch(req)));
  }
});
`);
  },
};

/** Backend down in dev: answer 503 like the AWS load balancer does, so the app switches to offline mode (not a 500). */
const target = (url) => ({
  target: url,
  configure: (proxy) => proxy.on('error', (err, req, res) => {
    if (res.writeHead && !res.headersSent) res.writeHead(503, { 'Content-Type': 'text/plain' }).end('Backend unreachable');
  }),
});

const proxy = {
  '/api': target(api),
  '/files': target(api),
  // Google/Facebook sign-in: the redirect + callback must go through the same origin as the app
  '/oauth2': target(api),
  '/login/oauth2': target(api),
  '/ws': { target: api.replace(/^http/, 'ws'), ws: true },
};

export default defineConfig({
  plugins: [react(), cspPlugin, swPlugin],
  server: { port: Number(process.env.PORT ?? 5173), proxy },
  // `npm run preview` serves the production build (with the CSP) through the same proxy
  preview: { port: Number(process.env.PORT ?? 4173), proxy },
  // SQLite's wasm build loads sqlite3.wasm relative to its own module, which pre-bundling would break
  optimizeDeps: { exclude: ['@sqlite.org/sqlite-wasm'] },
  worker: { format: 'es' },
});
